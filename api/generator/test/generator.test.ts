// Spec 0014 GNR-10: the fixture contract renders every target to the committed snapshots, byte for byte, and bad
// input fails naming the operation. Rewrite the snapshots with ORVANO_SNAPSHOT_WRITE=1 (the server's convention).
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import {
  GeneratorError,
  loadContract,
  parseContract,
  type OpenApiDocument,
} from "../src/contract.ts";
import { loadConformance, type ConformanceInputs } from "../src/conformance.ts";
import { generate } from "../src/generate.ts";
import { writeOutput, type OutputFile } from "../src/output.ts";
import { findTarget, targetNames } from "../src/targets/index.ts";

const here = dirname(fileURLToPath(import.meta.url));
const fixturePath = join(here, "fixtures", "contract.openapi.json");
const conformanceDir = join(here, "fixtures", "conformance");
const snapshotRoot = join(here, "snapshots");
const commit = "0123456789abcdef0123456789abcdef01234567";
const writeSnapshots = process.env["ORVANO_SNAPSHOT_WRITE"] === "1";

function fixture(): OpenApiDocument {
  return JSON.parse(readFileSync(fixturePath, "utf8")) as OpenApiDocument;
}

function render(document: OpenApiDocument, target: string): OutputFile[] {
  return generate(
    parseContract(new TextEncoder().encode(JSON.stringify(document, null, 2))),
    conformance(),
    target,
    commit,
  );
}

function conformance(): ConformanceInputs {
  return loadConformance(conformanceDir);
}

function contentOf(files: OutputFile[], path: string): string | undefined {
  return files.find((file) => file.path === path)?.content;
}

/** A thunk that renders the document for ts-server, for `toThrow`. */
function rendering(document: OpenApiDocument): () => OutputFile[] {
  return () => render(document, "ts-server");
}

function filesUnder(root: string): string[] {
  if (!existsSync(root)) return [];
  return readdirSync(root, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(root, join(entry.parentPath, entry.name)).split("\\").join("/"))
    .toSorted();
}

describe("0014 AC-14: the generator renders the fixture contract", () => {
  for (const target of targetNames) {
    it(`0014 AC-14: ${target} matches its committed snapshot`, () => {
      const files = generate(loadContract(fixturePath), conformance(), target, commit);
      const root = join(snapshotRoot, target);
      if (writeSnapshots) {
        rmSync(root, { recursive: true, force: true });
        writeOutput(root, findTarget(target).ownership, files);
      }
      expect(files.map((file) => file.path)).toEqual(filesUnder(root));
      for (const file of files) {
        expect(file).toEqual({
          path: file.path,
          content: readFileSync(join(root, file.path), "utf8"),
        });
      }
    });

    it(`0014 AC-14: ${target} gives the same bytes on every run`, () => {
      expect(generate(loadContract(fixturePath), conformance(), target, commit)).toEqual(
        generate(loadContract(fixturePath), conformance(), target, commit),
      );
    });

    it(`0014 AC-14: every ${target} file names the commit, the contract version, and its hash`, () => {
      const { sha256 } = loadContract(fixturePath);
      const line = `Generated by @orvano/sdk-generator ${commit} from contract 2026-10-22 (sha256 ${sha256.slice(0, 12)}). Do not edit.`;
      for (const file of generate(loadContract(fixturePath), conformance(), target, commit)) {
        // JSON has no comments, so a JSON file names its source in a top level "generated" member.
        const head = file.path.endsWith(".json")
          ? [(JSON.parse(file.content) as { generated: string }).generated]
          : file.content.split("\n").slice(0, 2);
        const expected = file.path.endsWith(".json") ? [line] : ["// @generated", `// ${line}`];
        expect({ path: file.path, head, carriageReturn: file.content.includes("\r") }).toEqual({
          path: file.path,
          head: expected,
          carriageReturn: false,
        });
      }
    });
  }

  it("0014 AC-14: a client target has only client operations, a server target has every public one", () => {
    const client = generate(loadContract(fixturePath), conformance(), "ts-client", commit);
    const server = generate(loadContract(fixturePath), conformance(), "ts-server", commit);
    expect(contentOf(client, "src/generated/widget-keys-service.ts")).toBeUndefined();
    expect(contentOf(client, "src/generated/models.ts")).not.toContain("WidgetKeyResponse");
    expect(contentOf(client, "src/generated/widgets-service.ts")).not.toContain(
      "Fixture_DeleteWidget",
    );
    expect(contentOf(client, "src/generated/widgets-service.ts")).toContain("Fixture_GetWidget");

    expect(contentOf(server, "src/generated/widget-keys-service.ts")).toContain(
      "Fixture_RotateWidgetKey",
    );
    expect(contentOf(server, "src/generated/widgets-service.ts")).toContain("Fixture_DeleteWidget");
    expect(contentOf(server, "src/generated/widgets-service.ts")).toContain("Fixture_GetWidget");

    const scenarioIds = (files: OutputFile[]): string[] =>
      (
        JSON.parse(contentOf(files, "conformance/scenarios.generated.json") ?? "{}") as {
          scenarios: { id: string }[];
        }
      ).scenarios.map((scenario) => scenario.id);
    expect(scenarioIds(client)).not.toContain("widget_keys.rotate.ok");
    expect(scenarioIds(server)).toContain("widget_keys.rotate.ok");
    expect(contentOf(client, "conformance/dispatch.generated.ts")).not.toContain(
      '"widgetKeys.rotate"',
    );
    expect(contentOf(server, "conformance/dispatch.generated.ts")).toContain('"widgetKeys.rotate"');
  });

  it("0014 AC-14: the real contract renders every target", () => {
    const contract = loadContract(join(here, "..", "..", "openapi.json"));
    const missingHealth = targetNames.filter(
      (target) =>
        !generate(
          contract,
          loadConformance(join(here, "..", "..", "conformance")),
          target,
          commit,
        ).some((file) => file.content.includes(`"Host_Health"`)),
    );
    expect(missingHealth).toEqual([]);
  });
});

describe("0014 GNR-10: bad input fails naming the operation", () => {
  it("a missing x-orvano-sdk", () => {
    const document = fixture();
    const operation = document.paths?.["/v1/projects/{projectId}/widgets"]?.post;
    if (operation !== undefined) delete operation["x-orvano-sdk"];
    expect(rendering(document)).toThrow(GeneratorError);
    expect(rendering(document)).toThrow(/^Fixture_CreateWidget: the operation has no x-orvano-sdk/);
  });

  it("an unresolved reference", () => {
    const document = fixture();
    const operation = document.paths?.["/v1/projects/{projectId}/widgets/{widgetId}"]?.get;
    const response = operation?.responses?.["200"]?.content?.["application/json"];
    if (response !== undefined) response.schema = { $ref: "#/components/schemas/Missing" };
    expect(rendering(document)).toThrow(
      /^Fixture_GetWidget response 200: unresolved reference #\/components\/schemas\/Missing/,
    );
  });

  it("two operations with the same name in one service", () => {
    const document = fixture();
    const operation = document.paths?.["/v1/projects/{projectId}/widgets/{widgetId}"]?.delete;
    if (operation !== undefined) operation["x-orvano-sdk"] = { service: "widgets", method: "get" };
    expect(rendering(document)).toThrow(
      /^Fixture_GetWidget: widgets\.get is also the SDK name of Fixture_DeleteWidget/,
    );
  });

  it("an input name used twice", () => {
    const document = fixture();
    const schema = document.components?.schemas?.["CreateWidgetRequest"];
    if (schema?.properties !== undefined)
      schema.properties["projectId"] = { type: "string", description: "Clash." };
    const operation = document.paths?.["/v1/projects/{projectId}/widgets"]?.post;
    operation?.parameters?.push({
      name: "projectId",
      in: "query",
      description: "Clash.",
      schema: { type: "string" },
    });
    expect(rendering(document)).toThrow(
      /^Fixture_CreateWidget: the input name projectId is used twice/,
    );
  });

  it("an error code missing from the catalogue", () => {
    const document = fixture();
    const operation = document.paths?.["/v1/projects/{projectId}/widgets"]?.post;
    if (operation !== undefined) operation["x-orvano-errors"] = ["widget_gone"];
    expect(rendering(document)).toThrow(/^Fixture_CreateWidget: x-orvano-errors lists widget_gone/);
  });

  it("a schema name that takes a runtime name", () => {
    const document = fixture();
    const schemas = document.components?.schemas;
    const operation = document.paths?.["/v1/health"]?.get;
    const response = operation?.responses?.["200"]?.content?.["application/json"];
    if (schemas !== undefined && response !== undefined) {
      schemas["OrvanoError"] = { type: "object", description: "Clash.", properties: {} };
      response.schema = { $ref: "#/components/schemas/OrvanoError" };
    }
    expect(rendering(document)).toThrow(
      /^schema OrvanoError: the TypeScript name OrvanoError is also used by the runtime/,
    );
  });

  it("a scenario that calls an operation the SDK does not have", () => {
    const inputs = conformance();
    const scenario = inputs.scenarios.find((entry) => entry.id === "health.get.ok");
    if (scenario?.steps[0] !== undefined) scenario.steps[0].call = "fixture.getWidget";
    expect(() => generate(loadContract(fixturePath), inputs, "ts-client", commit)).toThrow(
      /^Scenario health\.get\.ok: no client operation fixture\.getWidget for a live scenario/,
    );
  });

  it("an unknown target", () => {
    expect(() => findTarget("ts-browser")).toThrow(/^Unknown target ts-browser\. Targets: /);
  });
});

describe("0014 GNR-9: the generator rewrites only what its target owns", () => {
  it("deletes and rewrites src/generated and src/runtime, and leaves the rest", () => {
    const root = mkdtempSync(join(tmpdir(), "orvano-generator-"));
    try {
      for (const [path, content] of [
        ["src/index.ts", "hand written\n"],
        ["src/generated/old-service.ts", "stale\n"],
        ["src/runtime/old.ts", "stale\n"],
      ] as const) {
        mkdirSync(dirname(join(root, path)), { recursive: true });
        writeFileSync(join(root, path), content);
      }
      const target = findTarget("ts-client");
      writeOutput(
        root,
        target.ownership,
        generate(loadContract(fixturePath), conformance(), "ts-client", commit),
      );
      const written = filesUnder(root);
      expect(written).toContain("src/index.ts");
      expect(readFileSync(join(root, "src/index.ts"), "utf8")).toBe("hand written\n");
      expect(written).not.toContain("src/generated/old-service.ts");
      expect(written).not.toContain("src/runtime/old.ts");
      expect(written).toContain("src/generated/widgets-service.ts");
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("refuses a file outside what the target owns", () => {
    const root = mkdtempSync(join(tmpdir(), "orvano-generator-"));
    try {
      expect(() => {
        writeOutput(root, findTarget("ts-client").ownership, [
          { path: "src/index.ts", content: "" },
        ]);
      }).toThrow(/does not own/);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});
