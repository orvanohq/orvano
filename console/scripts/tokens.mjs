// Writes src/styles/tokens.css from the design system's tokens.json (spec 0003, "Token generation").
//   node scripts/tokens.mjs           write the file
//   node scripts/tokens.mjs --check   exit 1 when the committed file differs from what this would write
// The console never edits tokens.css by hand: change tokens.json, then run `pnpm --filter @orvano/console tokens`.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(
  here,
  "../../docs/design/design-system/tokens.json",
);
const target = path.resolve(here, "../src/styles/tokens.css");

const tokens = JSON.parse(await readFile(source, "utf8"));

const declare = (name, value) => `  --${name}: ${value};`;

const colours = tokens.color.tokens;
const light = colours.map((t) => declare(t.name, t.value.light));
const dark = colours.map((t) => declare(t.name, t.value.dark));
const spacing = tokens.spacing.tokens.map((t) => declare(t.name, t.value));
const radius = tokens.radius.tokens.map((t) => declare(t.name, t.value));
const shadow = tokens.shadow.tokens.map((t) => declare(t.name, t.value));
const families = Object.entries(tokens.type.families).map(([name, value]) =>
  declare(`font-${name}`, value),
);

// The type scale becomes Tailwind text sizes (text-h1, text-body, text-mono-small) with line height and weight.
const typeScale = tokens.type.groups.flatMap((group) =>
  group.styles.flatMap((style) => [
    declare(`text-${style.name}`, style.fontSize),
    declare(`text-${style.name}--line-height`, style.lineHeight),
    declare(`text-${style.name}--font-weight`, String(style.fontWeight)),
  ]),
);

const css = `/*
 * Generated by console/scripts/tokens.mjs from docs/design/design-system/tokens.json.
 * Do not edit. Change tokens.json, then run: pnpm --filter @orvano/console tokens
 * Dark values apply when next-themes writes data-theme="dark" on <html> (System resolves to light or dark).
 */

:root {
${[...light, ...spacing, ...radius, ...shadow, ...families].join("\n")}
}

:root[data-theme="dark"] {
${dark.join("\n")}
}

/* Tailwind theme values: radius, shadow, fonts and the type scale, as utilities (rounded-md, shadow-popover, text-h1). */
@theme {
${[...radius, ...shadow, ...families, ...typeScale].join("\n")}
}
`;

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== css) {
    console.error(
      "src/styles/tokens.css is out of date with docs/design/design-system/tokens.json. Run: pnpm --filter @orvano/console tokens",
    );
    process.exit(1);
  }
  console.log("tokens.css matches tokens.json.");
} else {
  await writeFile(target, css);
  console.log(`Wrote ${path.relative(process.cwd(), target)}.`);
}
